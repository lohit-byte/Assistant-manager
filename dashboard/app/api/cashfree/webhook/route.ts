import { NextResponse } from 'next/server'
import { createClient } from '@supabase/supabase-js'
import crypto from 'crypto'
import { buildSubscriptionUpsert, planById } from '@/lib/plans'
import { upsertGuildSubscription } from '@/lib/subscription'

const supabaseAdmin = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY!,
)

function safeCompare(a: string, b: string): boolean {
  const bufA = Buffer.from(a)
  const bufB = Buffer.from(b)
  if (bufA.length !== bufB.length) return false
  return crypto.timingSafeEqual(bufA, bufB)
}

export async function POST(request: Request) {
  try {
    const rawBody = await request.text()
    const signature = request.headers.get('x-webhook-signature')
    const timestamp = request.headers.get('x-webhook-timestamp')
    const secret = process.env.CASHFREE_SECRET_KEY!

    if (!signature || !timestamp || !secret) {
      return NextResponse.json({ status: 'ignored' }, { status: 200 })
    }

    const expectedSignature = crypto
      .createHmac('sha256', secret)
      .update(timestamp + rawBody)
      .digest('base64')

    if (!safeCompare(expectedSignature, signature)) {
      console.warn('Cashfree webhook: signature mismatch')
      return NextResponse.json({ status: 'ignored' }, { status: 200 })
    }

    const body = JSON.parse(rawBody)

    if (body?.type !== 'PAYMENT_SUCCESS_WEBHOOK') {
      return NextResponse.json({ status: 'ok' })
    }

    const order = body?.data?.order
    if (!order || (order.order_status && order.order_status !== 'PAID')) {
      return NextResponse.json({ status: 'ignored' }, { status: 200 })
    }

    // Order ids are generated by /api/cashfree/create-order as g<guildId>_<planCode>_<random>.
    const orderId = String(order.order_id || '')
    const [guildPart, planCode] = orderId.split('_')
    const guildId = guildPart?.replace('g', '')
    const planId = planById(planCode)

    if (!guildId || !/^\d+$/.test(guildId) || !planId) {
      console.warn('Cashfree webhook: unrecognised order id', orderId)
      return NextResponse.json({ status: 'ignored' }, { status: 200 })
    }

    const { data: existing } = await supabaseAdmin
      .from('guilds')
      .select('premium_ends_at, last_order_id')
      .eq('guild_id', guildId)
      .maybeSingle()

    // Cashfree retries webhooks, so make delivery idempotent.
    if (existing?.last_order_id === orderId) {
      return NextResponse.json({ status: 'ok' })
    }

    const update = buildSubscriptionUpsert(existing ?? null, planId, orderId)
    await upsertGuildSubscription(supabaseAdmin, guildId, update)

    console.log(`✅ Upgraded guild ${guildId} to ${planId} until ${update.premium_ends_at}`)
    return NextResponse.json({ status: 'ok' })
  } catch (error) {
    console.error('Webhook Error:', error)
    return NextResponse.json({ status: 'error' }, { status: 500 })
  }
}
